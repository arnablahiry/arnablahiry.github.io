#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const XLSX = require('xlsx');

const repoRoot = path.resolve(__dirname, '..');
const workbookPath = path.join(repoRoot, 'data', 'news.xlsx');
const newsJsPath = path.join(repoRoot, 'scripts', 'home', 'news-data.js');

function loadWindowKey(filePath, key) {
  if (!fs.existsSync(filePath)) return null;
  const code = fs.readFileSync(filePath, 'utf8');
  const sandbox = { window: {} };
  vm.runInNewContext(code, sandbox, { filename: filePath });
  return sandbox.window[key] || null;
}

function parseDate(value) {
  if (value instanceof Date) return value;
  const parsed = new Date(value);
  return Number.isNaN(parsed.getTime()) ? new Date(0) : parsed;
}

if (!fs.existsSync(workbookPath)) {
  const wb = XLSX.utils.book_new();
  const sheetRows = [
    ['Title', 'Link', 'Date'],
    ['Example: Paper accepted at Conference X', 'https://example.com', '2026-06-01']
  ];
  const ws = XLSX.utils.aoa_to_sheet(sheetRows);
  ws['!cols'] = [{ wch: 60 }, { wch: 50 }, { wch: 14 }];
  XLSX.utils.book_append_sheet(wb, ws, 'News');
  fs.mkdirSync(path.dirname(workbookPath), { recursive: true });
  XLSX.writeFile(wb, workbookPath);
  console.log(`Created template at ${path.relative(repoRoot, workbookPath)}. Fill it in and rerun this script.`);
  process.exit(0);
}

const workbook = XLSX.readFile(workbookPath);
const sheetName = workbook.SheetNames[0];
const ws = workbook.Sheets[sheetName];
const rows = XLSX.utils.sheet_to_json(ws, { header: 1, raw: false });

const items = [];
for (let i = 1; i < rows.length; i += 1) {
  const row = rows[i] || [];
  const title = row[0] == null ? '' : String(row[0]).trim();
  const link = row[1] == null ? '' : String(row[1]).trim();
  const date = row[2] == null ? '' : String(row[2]).trim();
  if (!title) continue;
  items.push({ title, link, date });
}

items.sort((a, b) => parseDate(b.date) - parseDate(a.date));
const top5 = items.slice(0, 5);

const existing = loadWindowKey(newsJsPath, 'NEWS_ITEMS');
if (existing && JSON.stringify(existing) === JSON.stringify(top5)) {
  console.log('No changes to news items.');
  process.exit(0);
}

const jsBody = [
  '/* Auto-generated by scripts/sync-news-spreadsheet.js.',
  '   Edit data/news.xlsx and rerun the script. */',
  '(function () {',
  `  window.NEWS_ITEMS = ${JSON.stringify(top5, null, 2).replace(/\n/g, '\n  ')};`,
  '})();',
  ''
].join('\n');

fs.mkdirSync(path.dirname(newsJsPath), { recursive: true });
fs.writeFileSync(newsJsPath, jsBody, 'utf8');

console.log(`Synced ${top5.length} news items (of ${items.length} total) to ${path.relative(repoRoot, newsJsPath)}.`);
